def envelope_line(h, s0, i):
    """Falling (or flat) line from the high at s0 that covers every high from s0+1 to i-1; None if rising."""
    if i - s0 < 3:
        return None
    t = np.arange(s0 + 1, i)
    sl = float(np.max((h[s0 + 1:i] - h[s0]) / (t - s0)))
    if sl > 0:
        return None
    return lambda k: h[s0] + sl * (k - s0)


