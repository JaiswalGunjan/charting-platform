@rule("S4-R002", "S4-R003", "S4-R004", "S4-R007", "S4-R008", "S4-R009", "S4-R010", "S4-R011", "S4-R012",
      "S4-R013", "S4-R016", "S4-R017", "S7-R016", "S1-R073", "S4-R001")
def one_two_three(b, i):
    """1-2-3 shaper: read the MACD histogram right to left from the bar before i: wave 3 down, wave 2 up (any length),
    wave 1 down (S4-R002); peak 1 = price swing high where wave 1 starts, peak 2 = swing high of wave 2; line through
    them (falling or flat, S4-R007); signal = first close above the line (S4-R003) on pocket-pivot volume (S4-R004).
    A line already broken by a close is discarded (S4-R009); the whole pattern lasts at most one23_max_bars (S4-R011)."""
    cfg = b.cfg
    hist, h, c = b.macdh, b.h, b.c
    start = max(2, i - cfg.get("one23_max_bars", 33) - 5)
    runs = tick_runs(hist, i - 1, start)
    if len(runs) < 3 or runs[-1][0] != -1 or runs[-2][0] != 1 or runs[-3][0] != -1:
        return None
    w1, w2 = runs[-3], runs[-2]
    a1 = max(0, w1[1] - 3)
    p1 = a1 + int(np.argmax(h[a1:w1[1] + 1]))
    p2 = w2[1] + int(np.argmax(h[w2[1]:w2[2] + 2]))
    if p2 <= p1 or i - p1 > cfg.get("one23_max_bars", 33):
        return None
    h1, h2 = h[p1], h[p2]
    if h2 > h1 * 1.005:
        return None
    sl = (h2 - h1) / (p2 - p1)
    line = lambda k: h2 + sl * (k - p2)                       # noqa: E731
    if not (c[i] > line(i) and c[i - 1] <= line(i - 1)):
        return None
    if p2 + 1 < i - 1 and np.any(c[p2 + 1:i - 1] > line(np.arange(p2 + 1, i - 1))):
        return None                                          # earlier close above: failed line (S4-R009)
    hit = Hit("ONE23", "SL_MACDH", rules=["S4-R002", "S4-R003"])
    hit.notes.append(f"1-2-3: line through peak 1 {h1:.2f} ({b.date(p1)}) and peak 2 {h2:.2f} ({b.date(p2)}); "
                     f"close {c[i]:.2f} above the line at {line(i):.2f}")
    hit.extra["geom"] = dict(kind="line", p1=int(p1), p2=int(p2), h1=float(h1), h2=float(h2),
                             line_now=float(line(i)), w1=[int(w1[1]), int(w1[2])], w2=[int(w2[1]), int(w2[2])],
                             w3=[int(runs[-1][1]), int(runs[-1][2])])          # chart geometry (swingbt.scan)
    if cfg.get("one23_needs_pp", True):
        if b.pp[i]:
            hit.rules.append("S4-R004")
        else:
            hit.reject.append(("S4-R004", "1-2-3 breakout without pocket-pivot volume"))
    pp_count = int(np.sum(b.pp[p1:i]))
    hit.extra["pp_in_pattern"] = pp_count                       # S4-R012
    if np.mean(b.v[p2:i]) < np.mean(b.v[p1:p2 + 1]):
        hit.rules.append("S4-R013")
    if any(b.cic22[max(0, i - 30):i]):
        hit.rules.append("S4-R016")
        hit.extra["near_cic"] = True
    return hit


