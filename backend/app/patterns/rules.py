@rule("S1-R074", "S1-R048", "S1-R011", "S1-R079", "S1-R016", "S5B-R003", "S5B-R010", "S1-R068")
def quiet_breakout(b, i):
    """Breakout from a quiet zone with light traffic at resistance: the 5 bars before had a smaller mean range than the
    20 before and below-average volume (S1-R011/R074), the prior close was within 5% of the 20-bar high, then a close
    above that high on >= 1.4x the 50-day volume with up-day volume beating down-day volume in the base (S1-R079)."""
    if i < 25 or not (b.c[i] > b.high_20[i] and b.c[i - 1] <= b.high_20[i - 1]):
        return None
    if not b.v[i] >= 1.4 * b.vol50[i]:
        return None
    if not (np.nanmean(b.range_pct[i - 5:i]) < np.nanmean(b.range_pct[i - 25:i - 5]) and
            np.mean(b.v[i - 5:i]) < b.vol50[i]):
        return None
    if b.c[i - 1] < b.high_20[i - 1] * 0.95:
        return None
    hit = Hit("QUIET_BO", "SL_BO_DAY", rules=["S1-R074", "S1-R011"])
    hit.notes.append(f"Quiet-zone breakout: 5-bar range and volume contracted; close {b.c[i]:.2f} above the 20-bar high "
                     f"{b.high_20[i]:.2f} on {b.v[i] / b.vol50[i]:.1f}x volume")
    hit.extra["geom"] = dict(kind="level", level=float(b.high_20[i]), level_from=int(i - 20), quiet=[int(i - 5), int(i - 1)],
                             ref=[int(i - 25), int(i - 6)])
    ud = _updown_vol(b, i - 20, i)
    if np.isfinite(ud) and ud > 1:
        hit.rules.append("S1-R079")
    else:
        hit.weak.append(("S1-R079", f"up/down volume {ud:.2f} <= 1 in the base"))
    return hit


