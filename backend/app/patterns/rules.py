@rule("S3-R049", "S1-R046", "S1-R059", "S1-R063", "S2B-R033", "S3-R012")
def natural_reaction(b, i):
    """Natural reaction (tennis ball): after a breakout above a 40-bar high and an extension of >= 5%, price pulls back
    to the old resistance and holds it (low >= 97% of the level) while range and volume contract; entry = close above
    the pullback's last 3 highs (S3-R049). Stop below the retest low."""
    for k in range(i - 4, max(45, i - 30), -1):
        level = b.h[k - 40:k].max()
        if not (b.c[k] > level and b.c[k - 1] <= level):
            continue
        if b.h[k:i].max() < level * 1.05:
            return None
        pull_lo = b.l[k + 1:i].min()
        if not (level * 0.97 <= pull_lo <= level * 1.04):
            return None
        if np.nanmean(b.range_pct[i - 5:i]) >= np.nanmean(b.range_pct[i - 20:i]) or \
                np.mean(b.v[i - 10:i]) >= b.vol50[i]:
            return None
        if not b.c[i] > b.h[i - 3:i].max():
            return None
        lo5 = b.l[i - 5:i + 1].min()
        hit = Hit("NAT_REACTION", "SL_PATTERN", rules=["S3-R049", "S1-R046"], stop=lo5,
                  stop_why="below the retest low (the old resistance must hold)")
        hit.notes.append(f"Natural reaction: breakout above {level:.2f} on {b.date(k)}, pullback held the level "
                         f"(low {pull_lo:.2f}) on contracting range and volume; close above the pullback highs")
        lo5_bar = int(i - 5 + np.argmin(b.l[i - 5:i + 1]))
        hit.extra["stop_bar"] = lo5_bar
        hit.extra["geom"] = dict(kind="level", bo_bar=int(k), level=float(level), level_from=int(k - 40),
                                 pull_lo=float(pull_lo), pull_lo_bar=int(k + 1 + np.argmin(b.l[k + 1:i])),
                                 ext_hi=float(b.h[k:i].max()), ext_hi_bar=int(k + np.argmax(b.h[k:i])),
                                 lo5=float(lo5), lo5_bar=lo5_bar)
        return hit
    return None


