@rule("S4-R033", "S4-R034", "S4-R035", "S4-R036", "S2-R054", "S8-R006", "S5A-R035", "S4-R038")
def bad_break_recovery(b, i):
    """Bad break recovery: a shallow shakeout close below the 50 (or 21) SMA (< 30% off the 52-week high), then a
    reclaim close above it on pocket-pivot volume (S4-R033/R034); the buy is the follow-up pocket pivot within 15 bars
    while every close holds above the average (S4-R035)."""
    cfg = b.cfg
    if not b.pp[i]:
        return None
    win = cfg.get("bbr_followup_window", 15)
    rw = cfg.get("bbr_reclaim_window", 10)
    for j in range(i - 1, max(rw + 1, i - win - 1), -1):
        if not b.pp[j]:
            continue
        for name in ("sma50", "sma21"):
            ma = getattr(b, name)
            if not (b.c[j] > ma[j]):
                continue
            broke = np.any(b.c[j - rw:j] < ma[j - rw:j])
            dd = (1 - b.l[j - rw:j].min() / b.high_52w[j]) * 100
            if broke and dd < cfg.get("bbr_max_drawdown_pct", 30) and np.all(b.c[j:i + 1] > ma[j:i + 1] * 0.99):
                hit = Hit("BBR", "SL_MACDH", rules=["S4-R033", "S4-R034", "S4-R035"])
                hit.notes.append(f"Bad break recovery: reclaimed the {name.upper()} on pocket-pivot volume on "
                                 f"{b.date(j)} after a {dd:.0f}% shakeout; follow-up pocket pivot today")
                hit.extra["bbr_ma"] = name
                hit.extra["geom"] = dict(kind="bbr", reclaim_bar=int(j), ma=name, broke_window=[int(j - rw), int(j - 1)],
                                         shakeout_low=float(b.l[j - rw:j].min()),
                                         shakeout_bar=int(j - rw + np.argmin(b.l[j - rw:j])), dd_pct=float(dd))
                return hit
    return None


