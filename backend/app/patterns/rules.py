def base_shape(b, i):
    """The base before bar i: left top = highest high of the prior base_lookback bars; depth, length, prior advance,
    handle (last 15 bars), volume dry-up, up/down volume ratio (as rule_metrics.pattern_block)."""
    lb = b.cfg.get("base_lookback", 130)
    lo = max(0, i - lb)
    if i - lo < 12:
        return None
    j = lo + int(np.argmax(b.h[lo:i]))
    top = b.h[j]
    n = i - j
    if n < 10:
        return None
    low = b.l[j:i].min()
    depth = (1 - low / top) * 100
    a0 = max(0, j - lb)
    adv = (top / b.l[a0:j + 1].min() - 1) * 100 if j > a0 else 0.0
    adv52 = (top / b.low_52w[j] - 1) * 100
    h15 = b.h[i - 15:i].max()
    handle = (1 - b.l[i - 15:i].min() / h15) * 100
    dry = float(np.mean(b.v[i - 10:i]) / b.vol50[i]) if b.vol50[i] > 0 else np.nan
    return dict(top=top, top_i=j, len=n, depth=depth, low=low, adv=adv, adv52=adv52, handle=handle, dry=dry, h15=h15,
                updown=_updown_vol(b, j, i), bear=b.wma200_slope[j] < 0 if np.isfinite(b.wma200_slope[j]) else False)


