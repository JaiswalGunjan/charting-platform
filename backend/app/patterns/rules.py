@rule("S3-R051", "S3-R052", "S1-R058", "S1-R054", "S1-R055", "S3-R018", "S2B-R036", "SD-R019")
def squat(b, i):
    """Squat: after a breakout above a 40-bar high, a close back below the level (shakeout), a reclaim within 10 bars,
    at least 3 bars holding above the level on below-average volume, then the buy on another wave of accumulation:
    a pocket-pivot or 22-day CIC bar (S3-R051/R052). Never the first close back above."""
    if not (b.pp[i] or b.cic22[i]):
        return None
    for k in range(i - 6, max(45, i - 40), -1):
        level = b.h[k - 40:k].max()
        if not (b.c[k] > level and b.c[k - 1] <= level):
            continue
        below = [m for m in range(k + 1, i) if b.c[m] < level]
        if not below:
            return None
        m = below[-1]
        hold = np.arange(m + 1, i)
        if len(hold) < 3 or not (b.l[hold] > level * 0.995).all() or np.mean(b.v[hold]) >= b.vol50[i]:
            return None
        if m - below[0] > 10:
            return None
        lo = b.l[m:i + 1].min()
        hit = Hit("SQUAT", "SL_PATTERN", rules=["S3-R051", "S3-R052"], stop=b.l[hold].min(),
                  stop_why="below the hold above the reclaimed level")
        hit.notes.append(f"Squat: breakout above {level:.2f} ({b.date(k)}), closed back below on {b.date(m)} (low "
                         f"{lo:.2f}), held above it for {len(hold)} bars on light volume; pocket-pivot/CIC bar today")
        hit.extra["stop_bar"] = int(hold[int(np.argmin(b.l[hold]))])
        hit.extra["geom"] = dict(kind="level", bo_bar=int(k), level=float(level), level_from=int(k - 40),
                                 below_first=int(below[0]), below_last=int(m), hold=[int(m + 1), int(i - 1)],
                                 hold_low=float(b.l[hold].min()))
        return hit
    return None


