@rule("S4-R022", "S4-R023", "S4-R024", "S4-R025", "S4-R026", "S4-R027", "S4-R028", "S2-R062", "SD-R017",
      "S5A-R036")
def oversold_shaper(b, i):
    """Oversold shaper: SMA50 > SMA200 with slow stochastic (5-3-3) < 20 while EMA10 > EMA20 in the last 12 bars
    (S4-R022); line from the price high at the last MACD-histogram up-tick before the oversold reading, covering every
    correction high (S4-R023); entry = first close above it while EMA10 > EMA20 (S4-R026). Hard rules: WMA10 and WMA20
    both ticking up on the breakout (S4-R024) and a close above the AVWAPs from the last swing high and the 52-week
    high (S4-R028)."""
    cfg = b.cfg
    if not (b.sma50[i] > b.sma200[i]) or not (b.ema10[i] > b.ema20[i]):
        return None
    look = cfg.get("oversold_lookback", 12)
    lo = max(1, i - look)
    os_bars = np.flatnonzero((b.stoch_k[lo:i] < cfg.get("stoch_oversold", 20)) & (b.ema10[lo:i] > b.ema20[lo:i]))
    if not len(os_bars):
        return None
    j0 = lo + int(os_bars[0])
    hist = b.macdh
    s = None
    for k in range(j0, max(1, j0 - 40), -1):
        if hist[k] > hist[k - 1]:
            s = k
            break
    if s is not None:
        a = max(0, s - 1)
        s0 = a + int(np.argmax(b.h[a:s + 2]))
    else:
        a = max(0, j0 - 20)
