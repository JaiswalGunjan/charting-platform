def _updown_vol(b, a, i):
    up = b.v[a:i][b.up_day[a:i]]
    dn = b.v[a:i][b.down_day[a:i]]
    return float(up.mean() / dn.mean()) if len(up) and len(dn) and dn.mean() > 0 else np.nan


