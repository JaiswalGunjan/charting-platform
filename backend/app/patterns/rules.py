@rule("S4-R039", "S4-R040", "SD-R015", "S4-R042")
def three_touch_trendline(b, i):
    """Three-touch-point trendline: a falling or flat line from the base high touched at least three times (highs
    within 1.5% of it, S4-R039); entry on the first close above it (S4-R040)."""
    cfg = b.cfg
    look = cfg.get("tp3_lookback", 80)
    lo = max(0, i - look)
    if i - 10 <= lo:
        return None
    s0 = lo + int(np.argmax(b.h[lo:i - 9]))
    line = envelope_line(b.h, s0, i)
    if line is None or not (b.c[i] > line(i) and b.c[i - 1] <= line(i - 1)):
        return None
    tol = cfg.get("tp3_touch_tol_pct", 1.5) / 100
    t = np.arange(s0 + 2, i)
    near = b.h[s0 + 2:i] >= line(t) * (1 - tol)
    touches = 1 + int(np.sum(near & np.r_[True, ~near[:-1]]))          # count separate touch episodes
    if touches < cfg.get("tp3_min_touches", 3):
        return None
    hit = Hit("TL3", "SL_MACDH", rules=["S4-R039", "S4-R040"])
    hit.notes.append(f"Three-touch trendline: line from {b.h[s0]:.2f} ({b.date(s0)}) touched {touches} times; close "
                     f"{b.c[i]:.2f} above it at {line(i):.2f}")
    hit.extra["touches"] = touches
    hit.extra["geom"] = dict(kind="line", s0=int(s0), h0=float(b.h[s0]), line_now=float(line(i)), touches=touches,
                             touch_bars=[int(x) for x in s0 + 2 + np.flatnonzero(near & np.r_[True, ~near[:-1]])])
    return hit


