def breakout_ok(b, i, s):
    """First close above the base's left top on breakout volume (S3-R010: >= 1.5x the 50-day average, or a PP)."""
    if not (b.c[i] > s["top"] and b.c[i - 1] <= s["top"]):
        return False
    return bool(b.pp[i] or b.v[i] >= b.cfg.get("breakout_vol_mult", 1.5) * b.vol50[i])


