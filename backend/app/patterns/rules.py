@rule("S1-R061", "S1-R062", "S1-R067")
def resistance_level(b, i, look=60, band=0.02, min_touches=3):
    """Resistance where the bulk of price action stops: the swing-high cluster (2% band) with the most touches in the
    last `look` bars, ignoring single extreme wicks (S1-R061). Returns (level, touches) or (nan, 0)."""
    lo = max(2, i - look)
    hs = np.array([b.h[k] for k in range(lo, i - 2) if b.swing_high[k]])
    if len(hs) == 0:
        return np.nan, 0
    best, n = np.nan, 0
    for x in hs:
        m = hs[(hs >= x * (1 - band)) & (hs <= x * (1 + band))]
        if len(m) > n:
            best, n = float(np.median(m)), len(m)
    return (best, n) if n >= min_touches else (best, n)
