@rule("S4-R044", "S4-R045", "S4-R046", "S6A-R006", "S6A-R007", "S2B-R024", "S2B-R038", "S4-R018")
def mini_coil(b, i):
    """Mini coil: a pocket-pivot parent bar, then at least two bars inside its range (1.5% tolerance), then a close above
    the parent's high on pocket-pivot or strong (1.5x 50-day) volume (S4-R045, S6A-R007). A weak parent close is
    accepted only near both AVWAPs (S4-R046). Stop = breakout day's low (S6A-R006)."""
    cfg = b.cfg
    tol = cfg.get("coil_inside_tol_pct", 1.5) / 100
    for j in range(i - 1 - cfg.get("coil_min_bars", 2), max(0, i - cfg.get("coil_lookback", 20)), -1):
        if not b.pp[j]:
            continue
        hj, lj = b.h[j], b.l[j]
        ins = slice(j + 1, i)
        if not ((b.h[ins] <= hj * (1 + tol)).all() and (b.l[ins] >= lj * (1 - tol)).all() and (b.c[ins] <= hj).all()):
            return None
        if not (b.c[i] > hj):
            return None
        hit = Hit("MINICOIL", "SL_BO_DAY", rules=["S4-R045"])
        hit.notes.append(f"Mini coil: {i - j - 1} bars inside the pocket-pivot bar of {b.date(j)} ({lj:.2f}-{hj:.2f}); "
                         f"close {b.c[i]:.2f} above its high")
        if b.pp[i] or b.v[i] >= cfg.get("coil_breakout_vol_mult", 1.5) * b.vol50[i]:
            hit.rules.append("S6A-R007")
        else:
            hit.reject.append(("S6A-R007", "coil breakout without pocket-pivot or strong volume"))
        if b.close_pos[j] < 0.6:
            near = abs(b.c[i] / b.avwap_52wh[i] - 1) <= 0.05 and abs(b.c[i] / b.avwap_swing[i] - 1) <= 0.05
            if near:
                hit.rules.append("S4-R046")
            else:
                hit.reject.append(("S4-R046", "weak parent bar away from the AVWAPs"))
        hit.extra["coil"] = True
        hit.extra["geom"] = dict(kind="box", parent=int(j), hi=float(hj), lo=float(lj), inside=[int(j + 1), int(i - 1)])
        return hit
    return None


