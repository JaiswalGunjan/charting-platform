@rule("S3-R055", "S3-R056", "S6B-R017")
def momentum_riding(b, i):
    """Momentum riding: after a breakout from a fresh base (close above the prior 20-bar high) and a sharp first
    extension (>= 10%), the FIRST pullback of 4-10 bars to the 10 (or 20) WMA with WMA10 > WMA20 and no close below
    the 20 WMA (S3-R055); entry = close above the prior bar's high on pocket-pivot or above-average volume."""
    p0, p1 = b.cfg.get("momentum_pullback_bars", (4, 10))
    if not (b.wma10[i] > b.wma20[i]) or not b.c[i] > b.h[i - 1] or not (b.pp[i] or b.v[i] > b.vol50[i]):
        return None
    for k in range(i - p0 - 2, max(25, i - 30), -1):
        if not (b.c[k] > b.high_20[k] and b.c[k - 1] <= b.high_20[k - 1]):
            continue
        pk = k + int(np.argmax(b.h[k:i]))
        if b.h[pk] < b.c[k] * 1.10 or not (p0 <= i - pk <= p1 + 1):
            return None
        pull = slice(pk + 1, i)
        if not (b.l[pull].min() <= b.wma10[pk + 1:i].max() * 1.0 or b.l[pull].min() <= b.wma20[i] * 1.01):
            return None
        if (b.c[pull] < b.wma20[pull]).any():
            return None
        if np.any(b.l[k + 1:pk] <= b.wma10[k + 1:pk]):           # not the first pullback
            return None
        hit = Hit("MOMENTUM", "SL_PATTERN", rules=["S3-R055"], stop=b.l[pull].min(),
                  stop_why="below the first pullback's low")
        hit.notes.append(f"Momentum riding: breakout {b.date(k)}, extension to {b.h[pk]:.2f} (+"
                         f"{(b.h[pk] / b.c[k] - 1) * 100:.0f}%), first pullback of {i - pk - 1} bars to the 10/20 WMA")
        hit.extra["stop_bar"] = int(pk + 1 + np.argmin(b.l[pull]))
        hit.extra["geom"] = dict(kind="pullback", bo_bar=int(k), bo_level=float(b.high_20[k]), peak_bar=int(pk),
                                 peak=float(b.h[pk]), pull=[int(pk + 1), int(i - 1)], pull_lo=float(b.l[pull].min()))
        return hit
    return None


