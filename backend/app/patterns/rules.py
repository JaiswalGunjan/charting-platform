@rule("S3B-R001", "S3B-R002", "S3B-R003", "S3B-R005", "S3B-R006", "S3B-R007", "S3B-R008", "S3B-R009",
      "S3B-R014", "S3B-R016", "S3B-R017", "S3B-R020", "S3B-R021", "S3B-R004", "S1-R051", "S6A-R017", "S9A-R010",
      "S2B-R013", "S1-R069")
def pocket_pivot(b, i):
    """End-of-day pocket-pivot buy: up day on volume above every down-day volume of the prior 10 bars (S3B-R001),
    close above the 10 and 50 WMA (S3B-R006), low at or just around the 10 WMA (S3B-R008: <= 1% above buyable,
    >= 5% above = extended, rejected), strong close (S3B-R009), out of a quiet zone (S3B-R007); rejected in a
    V-shape recovery or below the 50 WMA (S3B-R020) and after three up days with a weak close (S3B-R014)."""
    cfg = b.cfg
    if not b.pp[i]:
        return None
    c, lo, w10, w50 = b.c[i], b.l[i], b.wma10[i], b.wma50[i]
    if not (c > w10 and c > w50):
        return None
    hit = Hit("PP", "SL_MACDH", rules=["S3B-R001", "S3B-R006"])
    hit.notes.append(f"Pocket pivot: volume {b.v[i]:,.0f} > highest down-day volume of the prior 10 bars "
                     f"({b.pp_maxdown[i]:,.0f}); close {c:.2f} above WMA10 {w10:.2f} and WMA50 {w50:.2f}")
    gap = (lo / w10 - 1) * 100
    if gap >= cfg.get("pp_extended_cut_pct", 5.0):
        hit.reject.append(("S3B-R008", f"extended PP: low {gap:.1f}% above the 10 WMA"))
    elif gap > cfg.get("pp_low_vs_wma10_max_pct", 1.0):
        hit.weak.append(("S3B-R008", f"low {gap:.1f}% above the 10 WMA (late)"))
    else:
        hit.rules.append("S3B-R008")
    if b.close_pos[i] < cfg.get("pp_close_pos_min", 0.6):
        hit.weak.append(("S3B-R009", f"close position {b.close_pos[i]:.2f} < {cfg.get('pp_close_pos_min', 0.6)}"))
    else:
        hit.rules.append("S3B-R009")
    if i >= 20 and np.nanmean(b.range_pct[i - 5:i]) < np.nanmean(b.range_pct[i - 20:i]):
        hit.rules.append("S3B-R007")
    else:
        hit.weak.append(("S3B-R007", "no range contraction before the PP"))
    k_low = i - 25 + int(np.argmin(b.l[max(0, i - 25):i + 1])) if i >= 25 else int(np.argmin(b.l[:i + 1]))
    if i - k_low < cfg.get("v_min_bars_since_low", 8) and b.c[k_low:i + 1].min() < w50:
        hit.reject.append(("S3B-R020", f"V-shape: PP {i - k_low} bars after the 25-day low through the 50 WMA"))
    run = 0
    for k in range(i - 1, max(0, i - 6), -1):
        if b.up_day[k]:
            run += 1
        else:
            break
    if run >= 3 and b.close_pos[i] < 0.5:
        hit.reject.append(("S3B-R014", "weak PP: already up three days in a row and a weak close"))
    if i >= 11 and b.fi[i] > np.nanmax(b.fi[i - 10:i]):
        hit.rules.append("S3B-R014")
        hit.notes.append("Force Index above its 10-day peak (strong PP)")
    if i >= 6 and b.c[i - 1] > b.c[i - 6] and np.polyfit(np.arange(5), b.v[i - 5:i], 1)[0] < 0:
        hit.weak.append(("S3B-R021", "bounce on falling volume before the PP"))
    hit.extra["pp_trail"] = int(np.sum(b.pp[max(0, i - 30):i]))          # S3B-R017
    hit.extra["geom"] = dict(kind="pp", bar=int(i), window=[int(max(0, i - 10)), int(i - 1)],
                             pp_maxdown=float(b.pp_maxdown[i]), wma10=float(w10), wma50=float(w50),
                             gap_pct=float(gap), k_low=int(k_low))                  # chart geometry (swingbt.scan)
    return hit

