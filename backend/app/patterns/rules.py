def tick_runs(hist, end, start):
    """Runs of the MACD-histogram tick direction over bars start..end: [(sign, first, last)], newest last."""
    d = np.sign(np.diff(hist[start - 1:end + 1]))
    runs = []
    for off, s in enumerate(d):
        k = start + off
        s = 1 if s > 0 else -1
        if runs and runs[-1][0] == s:
            runs[-1][2] = k
        else:
            runs.append([s, k, k])
    return runs


