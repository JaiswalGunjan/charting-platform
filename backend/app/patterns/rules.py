@rule("S2B-R003", "S2B-R004", "S2B-R005", "S2B-R006", "S2B-R007", "S2B-R008", "S2B-R034", "S2B-R041", "SD-R011",
      "S2B-R033", "S2B-R002", "S2B-R011", "S2-R066", "S1-R034")
def phases(b):
    """Phase per bar from WMA10/WMA20 only (S2B-R041): reversal extension (10 < 20, both falling, close under both;
    no entries, S2B-R003) -> wedge pop (up day whose high breaches both MAs while they stop falling, S2B-R005) ->
    bullish crossover (10 crosses above 20) -> MA crossback (first pullback to the 10 WMA with 10 > 20 rising,
    S2B-R007) -> base (closes back above the 10 WMA, rising swing lows, S2B-R034/SD-R011) -> base and break (close
    above the base high, S2B-R008) -> trend; a later pullback to the 10 WMA starts a new base (S2B-R033)."""
    c, h, l = b.c, b.h, b.l
    w10, w20 = b.wma10, b.wma20
    s10, s20 = b.wma10_slope5, b.wma20_slope5
    up = b.up_day
    ph = np.zeros(b.n, dtype=np.int8)
    base_hi = np.full(b.n, np.nan)          # high of the current base (prior bars)
    base_len = np.zeros(b.n, dtype=np.int32)
    st, b0, bhi, blow = NONE, -1, np.nan, np.nan
    for i in range(1, b.n):
        if not (np.isfinite(w20[i]) and np.isfinite(w20[i - 1])):
            continue
        crossed_up = w10[i] > w20[i] and w10[i - 1] <= w20[i - 1]
        crossed_dn = w10[i] < w20[i] and w10[i - 1] >= w20[i - 1]
        rev = w10[i] < w20[i] and s10[i] < 0 and s20[i] < 0 and c[i] < w10[i] and c[i] < w20[i]
        if rev:
            st = REV_EXT
        elif crossed_dn:
            st = NONE
        elif st in (REV_EXT, NONE) and w10[i] < w20[i] and up[i] and h[i] > max(w10[i], w20[i]) \
                and s10[i] >= 0 and s20[i] >= 0:
            st = WEDGE_POP
        elif crossed_up:
            st = CROSS
        elif st == CROSS and l[i] <= w10[i] and w10[i] > w20[i]:
            st = CROSSBACK
        elif st in (CROSSBACK, TREND) and c[i] > w10[i] and w10[i] > w20[i] and (st == CROSSBACK or l[i - 1] <= w10[i - 1]):
            st, b0, bhi, blow = BASE, i, h[i], l[i]
        elif st == BASE_BREAK:
            st = TREND
        if st == BASE:
            if i > b0 and c[i] > bhi and i - b0 >= 3 and s10[i] > 0 and s20[i] > 0:
                base_hi[i] = bhi
                base_len[i] = i - b0
                st = BASE_BREAK
            elif w10[i] < w20[i] or (i - b0 > 3 and l[i] < blow * 0.97):
                st = NONE                                  # structure broken (SD-R011)
            else:
                bhi, blow = max(bhi, h[i]), min(blow, l[i])
                base_hi[i], base_len[i] = bhi, i - b0
        if st == TREND and l[i] <= w10[i] and w10[i] > w20[i]:
            st, b0, bhi, blow = BASE, i, h[i], l[i]
        ph[i] = st
    return ph, base_hi, base_len


