def contractions(b, a, i):
    """Pullback depths (%) from each 2-bar fractal swing high to the next swing low inside [a, i) (VCP 'T's):
    [(depth %, swing low, swing-high bar, swing-low bar)]."""
    hs = [k for k in range(a, i - 2) if b.swing_high[k]]
    out = []
    for k in hs:
        nxt = [m for m in range(k + 1, i - 2) if b.swing_low[m]]
        if nxt:
            m = nxt[0]
            out.append(((1 - b.l[m] / b.h[k]) * 100, b.l[m], k, m))
    return out


