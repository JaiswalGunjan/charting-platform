from dataclasses import dataclass, field

import numpy as np


def rule(*ids):
    """Records the rulebook ids a function implements (swingbt.rules.registry.rule without the registry)."""
    def deco(fn):
        fn.rule_ids = ids
        return fn
    return deco


@dataclass
class Hit:
    setup: str
    stop_rule: str
    rules: list = field(default_factory=list)
    notes: list = field(default_factory=list)
    reject: list = field(default_factory=list)
    weak: list = field(default_factory=list)
    stop: float = None
    stop_why: str = ""
    size_mult: float = 1.0
    extra: dict = field(default_factory=dict)

    @property
    def valid(self):
        return not self.reject


